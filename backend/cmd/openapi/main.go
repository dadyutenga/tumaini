// Command openapi assembles docs/api/openapi.yaml from docs/api/base.yaml and
// the per-module path fragments in docs/api/fragments. With -check it fails
// when the committed file is out of date, so CI catches a forgotten rebuild.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"go.yaml.in/yaml/v3"
)

func main() {
	dir := flag.String("dir", "../docs/api", "API docs directory")
	check := flag.Bool("check", false, "fail if openapi.yaml is not up to date")
	flag.Parse()
	out, err := build(*dir)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	target := filepath.Join(*dir, "openapi.yaml")
	if *check {
		cur, err := os.ReadFile(target)
		if err != nil || !bytes.Equal(cur, out) {
			fmt.Fprintln(os.Stderr, "docs/api/openapi.yaml is out of date: run `go run ./cmd/openapi` in backend/")
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(target, out, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

var methods = map[string]bool{"get": true, "put": true, "post": true, "delete": true, "patch": true}

func build(dir string) ([]byte, error) {
	var base map[string]any
	raw, err := os.ReadFile(filepath.Join(dir, "base.yaml"))
	if err != nil {
		return nil, err
	}
	if err := yaml.Unmarshal(raw, &base); err != nil {
		return nil, fmt.Errorf("base.yaml: %w", err)
	}
	paths := map[string]map[string]any{}
	files, err := filepath.Glob(filepath.Join(dir, "fragments", "*.yaml"))
	if err != nil {
		return nil, err
	}
	sort.Strings(files)
	tags := map[string]bool{}
	for _, f := range files {
		raw, err := os.ReadFile(f)
		if err != nil {
			return nil, err
		}
		var frag struct {
			Paths map[string]map[string]any `yaml:"paths"`
		}
		if err := yaml.Unmarshal(raw, &frag); err != nil {
			return nil, fmt.Errorf("%s: %w", filepath.Base(f), err)
		}
		for p, ops := range frag.Paths {
			if !strings.HasPrefix(p, "/") || strings.Contains(p, ":") {
				return nil, fmt.Errorf("%s: path %q must start with / and use {param} form", filepath.Base(f), p)
			}
			if paths[p] == nil {
				paths[p] = map[string]any{}
			}
			for m, op := range ops {
				if _, dup := paths[p][m]; dup && methods[m] {
					return nil, fmt.Errorf("%s: %s %s is defined twice", filepath.Base(f), strings.ToUpper(m), p)
				}
				paths[p][m] = op
				if opm, ok := op.(map[string]any); ok {
					if ts, ok := opm["tags"].([]any); ok {
						for _, t := range ts {
							tags[fmt.Sprint(t)] = true
						}
					}
				}
			}
		}
	}
	base["paths"] = paths
	names := make([]string, 0, len(tags))
	for t := range tags {
		names = append(names, t)
	}
	sort.Strings(names)
	list := make([]map[string]string, len(names))
	for i, t := range names {
		list[i] = map[string]string{"name": t}
	}
	base["tags"] = list
	var buf bytes.Buffer
	buf.WriteString("# Generated by backend/cmd/openapi from docs/api/base.yaml and docs/api/fragments. Do not edit.\n")
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(base); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
